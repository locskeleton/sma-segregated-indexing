--  02-01: NAV=10,000,000  UNIT=1000  UNIT_PRICE=10,000     PNL=0        (T0)
--  05-01: NAV=10,440,000  UNIT=1000  UNIT_PRICE=10,440     PNL=440,000  (stock 10.44M, cash 0)
--  06-01: NAV=10,760,000  UNIT=1000  UNIT_PRICE=10,760     PNL=320,000  (stock 10.76M, cash 0)

PRINT '--- T_SI_NAV_DAILY (SI tổng hợp: composition + NAV + hiệu suất + cổ tức/phí) ---';
SELECT C_BUSINESS_DATE, C_CASH, C_STOCK_VALUE, C_TOTAL_ASSET, C_NAV, C_UNIT_PRICE, C_DAILY_PNL,
       C_CASH_DIVIDEND, C_CUSTODY_FEE, C_MGMT_FEE_ACCRUED
FROM T_SI_NAV_DAILY WHERE FK_SI_ID=1 ORDER BY C_BUSINESS_DATE;
-- KỲ VỌNG: 06-01 NAV=10.76M, UP=10760, PNL=320000; cash_dividend=50000, custody_fee=1000, mgmt=0 (ngày có sự kiện → loại vắng=0)
--          02-01 & 05-01: cả 3 cột = NULL (SI không có sự kiện phí/cổ tức → LEFT JOIN)
-- (cổ tức/phí từ T_CUSTOMER_FEE_INCOME J11 SUM lên SI — KHÔNG đổi NAV, chỉ tham khảo báo cáo)

PRINT '--- T_SI_NAV_CURRENT (current cấp SI: 1 dòng/SI, = ngày mới nhất 06-01) ---';
SELECT FK_SI_ID, C_CASH, C_STOCK_VALUE, C_TOTAL_ASSET, C_LAST_NAV, C_UNIT, C_LAST_UNIT_PRICE, C_LAST_BUSINESS_DATE
FROM T_SI_NAV_CURRENT WHERE FK_SI_ID=1;
-- KỲ VỌNG: 1 dòng — NAV=10.76M, UP=10760, last_business_date=2026-01-06 (= dòng mới nhất T_SI_NAV_DAILY)

PRINT '--- T_SI_INDEX_DAILY (danh mục mẫu) ---';
