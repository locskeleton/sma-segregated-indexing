PRINT '--- T_CUSTOMER_HOLDING_DAILY (snapshot dated thuần) ---';
SELECT C_BUSINESS_DATE, C_TICKER, C_QUANTITY, C_AVG_COST
FROM T_CUSTOMER_HOLDING_DAILY WHERE C_CUSTOMER_ID=1001 ORDER BY C_BUSINESS_DATE, C_TICKER;

PRINT '--- Biến động NET/ngày suy ra ON-DEMAND từ snapshot (LAG) — không lưu cột ---';
SELECT C_BUSINESS_DATE, C_TICKER, C_QUANTITY,
       C_QUANTITY - LAG(C_QUANTITY,1,0) OVER (PARTITION BY C_CUSTOMER_ID,C_SI_ID,C_TICKER ORDER BY C_BUSINESS_DATE) AS QTY_DELTA
FROM T_CUSTOMER_HOLDING_DAILY WHERE C_CUSTOMER_ID=1001 ORDER BY C_BUSINESS_DATE, C_TICKER;
-- KỲ VỌNG: 02-01 AAA=60000/BBB=80000 (prev=0); 05-01 & 06-01 delta=0 (holdings không đổi)
-- LƯU Ý: LAG này chỉ bắt entry/đổi-qty của mã CÒN trong snapshot ngày D. Mã BÁN HẾT (không còn row
--   ngày D) cần FULL OUTER JOIN 2 snapshot D vs D-1 để ra delta âm — dùng khi report turnover cần đầy đủ.

