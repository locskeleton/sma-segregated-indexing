    - Khóa chính surrogate: MỌI bảng (trừ T_MASTER_PORTFOLIO) có cột GUID `PK_<table>`
             UNIQUEIDENTIFIER DEFAULT NEWID() làm **CLUSTERED PRIMARY KEY** = khóa public API/UI
             (IDOR-safe, random). Khóa natural/bigint cũ → giữ làm `UQ_<table>_NK` UNIQUE
             (đảm bảo idempotency/MERGE/NOT EXISTS của engine). FK tham chiếu = `FK_<table>`.
