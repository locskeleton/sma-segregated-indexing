    - PK constraint: `PK_<table>` (trên cột GUID) | natural UNIQUE: `UQ_<table>_NK`
    - Stored procedure: prefix SP_   |   Function: prefix UDF_
  QUY CHUẨN DECIMAL: Tiền VND & Quantity = DECIMAL(20,0) (KHÔNG thập phân — VND không có hào);
    Giá = DECIMAL(18,4); % / return / fee_rate = DECIMAL(10,6); Unit & Unit Price = DECIMAL(18,6);
    Weight = DECIMAL(12,8); CA ratio = DECIMAL(18,8); index_value = DECIMAL(18,x).
  PK clustered GUID (NEWID) ⇒ fragmentation cao trên bảng ghi-khối-lớn → prod: FILLFACTOR + REORG/REBUILD
